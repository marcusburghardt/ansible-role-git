"""Validate Conventional Commit messages without changing Git state."""

import argparse
import json
import re
import sys
from pathlib import Path

CONVENTIONAL_TYPES = (
    "build",
    "chore",
    "ci",
    "docs",
    "feat",
    "fix",
    "perf",
    "refactor",
    "revert",
    "style",
    "test",
)
SUBJECT_PATTERN = re.compile(
    rf"^(?P<type>{'|'.join(CONVENTIONAL_TYPES)})"
    r"(?:\((?P<scope>[^()\r\n]+)\))?"
    r"(?P<breaking>!)?: (?P<description>\S.*)$"
)
TRAILER_PATTERN = re.compile(r"^[A-Za-z][A-Za-z0-9-]*: \S")
SIGNED_OFF_PATTERN = re.compile(
    r"^Signed-off-by: .+ <[^<>\s]+@[^<>\s]+>$", re.MULTILINE
)
ASSISTED_PATTERN = re.compile(r"^Assisted-by: .+ \([^()\r\n]+\)$", re.MULTILINE)
EXEMPT_MESSAGE_PATTERN = re.compile(r"^(?:Merge |Revert \"|fixup! |squash! |amend! )")


def validate_subject(subject: str, max_subject: int = 72) -> re.Match[str]:
    """Validate one Conventional Commits subject and return its parse."""
    errors = []
    if not subject:
        errors.append("subject is empty")
    if len(subject) > max_subject:
        errors.append(f"subject is {len(subject)} characters; limit is {max_subject}")
    if subject.endswith("."):
        errors.append("subject must not end with a period")
    match = SUBJECT_PATTERN.match(subject)
    if not match:
        allowed = ", ".join(CONVENTIONAL_TYPES)
        errors.append(
            "subject must match '<type>(<scope>): <description>' "
            f"with type one of: {allowed}"
        )
    if errors:
        raise ValueError("; ".join(errors))
    return match


def validate_commit_message(
    message: str,
    *,
    max_subject: int = 72,
    max_body: int = 72,
    require_signed_off_by: bool = True,
    require_assisted_by: bool = False,
) -> dict:
    """Validate a commit message without changing Git state."""
    if not message.strip():
        raise ValueError("commit message is empty")
    lines = message.splitlines()
    subject = lines[0].rstrip()
    if EXEMPT_MESSAGE_PATTERN.match(subject):
        return {"skipped": True, "reason": "autogenerated or temporary message"}
    match = validate_subject(subject, max_subject)
    errors = []
    for number, raw_line in enumerate(lines[1:], start=2):
        line = raw_line.rstrip()
        if not line:
            continue
        if TRAILER_PATTERN.match(line):
            continue
        if line.startswith(("http://", "https://")):
            continue
        if " " not in line and "\t" not in line:
            continue
        if len(line) > max_body:
            errors.append(
                f"body line {number} is {len(line)} characters; limit is {max_body}"
            )
    body = "\n".join(lines[1:])
    if require_signed_off_by and not SIGNED_OFF_PATTERN.search(body):
        errors.append("missing 'Signed-off-by: Name <email>' trailer")
    if require_assisted_by and not ASSISTED_PATTERN.search(body):
        errors.append("missing 'Assisted-by: <tool> (<model>)' trailer")
    if errors:
        raise ValueError("; ".join(errors))
    return {
        "skipped": False,
        "type": match["type"],
        "scope": match["scope"],
        "breaking": bool(match["breaking"]),
        "subject": subject,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--file", required=True, help="Commit message file")
    parser.add_argument("--max-subject", type=int, default=72)
    parser.add_argument("--max-body", type=int, default=72)
    parser.add_argument(
        "--require-signed-off-by",
        action=argparse.BooleanOptionalAction,
        default=True,
    )
    parser.add_argument(
        "--require-assisted-by",
        action=argparse.BooleanOptionalAction,
        default=False,
    )
    arguments = parser.parse_args()
    result = validate_commit_message(
        Path(arguments.file).read_text(encoding="utf-8"),
        max_subject=arguments.max_subject,
        max_body=arguments.max_body,
        require_signed_off_by=arguments.require_signed_off_by,
        require_assisted_by=arguments.require_assisted_by,
    )
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError) as error:
        print(f"commit_lint: {error}", file=sys.stderr)
        sys.exit(1)
